/* ── Idiomas ──
   El diccionario español es la fuente de la forma: `en` se declara como
   `Dict`, así que si falta una clave en inglés el build falla. */

export const locales = ['es', 'en'] as const
export type Locale = (typeof locales)[number]
export const defaultLocale: Locale = 'es'

export const localeNames: Record<Locale, string> = { es: 'ES', en: 'EN' }

export const isLocale = (v: string): v is Locale =>
  (locales as readonly string[]).includes(v)

/** Cambia el prefijo de idioma de una ruta: /es/gallery -> /en/gallery */
export function switchLocalePath(pathname: string, next: Locale): string {
  const parts = pathname.split('/').filter(Boolean)
  if (parts.length && isLocale(parts[0])) parts[0] = next
  else parts.unshift(next)
  return '/' + parts.join('/')
}

